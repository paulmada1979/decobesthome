export const bambooSeries = [bambooFenceSeries, bambooPanelSeries];

/** Images for a variant page (generated by scripts/build-bamboo-variants.mjs). */
export function variantImages(id: string) {
  return (
    bambooVariantImages[id] ?? { hero: "/images/bamboo-fence-hero.webp", gallery: [], qc: [] }
  );
}

/** Parent-page card → variant page link, keyed by parent slug then card image. */
export function variantHrefForCard(parentSlug: string, cardImg: string): string | undefined {
  const s = bambooSeries.find((x) => x.parent === parentSlug);
  const v = s?.variants.find((x) => x.card === cardImg);
  return s && v ? `/products/${s.parent}/${v.id}` : undefined;
}
